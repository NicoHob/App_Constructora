    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
//        String aux = lstObras.getSelectedValue();
        //verificar que hayan elementos seleccionados
        if(lstObras.getSelectedValue()!=null || lstGastos.getSelectedValue()!=null){
            String aux = lstObras.getSelectedValue();
            String aux2 = lstGastos.getSelectedValue();
            String obr = (aux.substring(0,aux.indexOf(" - ")));
            Obra obra = s.buscarObra(obr);
            String gastoRubro = aux2.substring(0,aux2.indexOf(" ($"));
            Gasto gasto = s.buscarGasto(gastoRubro, obra);
            gasto.setSePago(true);
            actualizarModel();
            javax.swing.JOptionPane.showMessageDialog(null, "Gasto Pagado", "Pago exitoso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }else{
            javax.swing.JOptionPane.showMessageDialog(null, "Seleccione datos", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        model.removeAllElements();
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

