    //metodo para actualizar la lista de gastos cada vez que se paga uno
    public void actualizarModel(){
        String aux = lstObras.getSelectedValue();
        String obr = (aux.substring(0 , aux.indexOf(" - ")));
        Obra obra = s.buscarObra(obr);
        model.removeAllElements();
        ArrayList<Gasto> gastos = obra.getGastos();
        for (Gasto g : gastos) {
            if (!g.getSePago()){
                model.addElement(g.getRubro().getNombre() + " ($" + g.getMonto() + ")");
            }
        }
    }
